async def seed():
    await init_db()
    async with AsyncSessionLocal() as db:
        # Check if already seeded
        from sqlalchemy import select, func
        count = await db.scalar(select(func.count(FaqCategory.id)))
        if count and count > 0:
            print("Already seeded, skipping.")
            return

        # Seed FAQ
        for order, cat_data in enumerate(FAQ_DATA):
            cat = FaqCategory(name=cat_data["name"], order=order, is_active=True)
            db.add(cat)
            await db.flush()
            for item_order, (question, answer) in enumerate(cat_data["items"]):
                item = FaqItem(
                    category_id=cat.id, question=question,
                    answer=answer, order=item_order, is_active=True
                )
                db.add(item)

        # Seed knowledge base
        for k in KNOWLEDGE_DATA:
            db.add(KnowledgeItem(updated_at=datetime.utcnow(), **k))

        # Seed GPT settings
        db.add(GptSettings(**DEFAULT_GPT_SETTINGS))

        await db.commit()
        print("✅ Seed complete: FAQ, Knowledge Base, GPT Settings")


if __name__ == "__main__":
    asyncio.run(seed())
